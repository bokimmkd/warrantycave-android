#!/usr/bin/env python3
"""Prepare local-only or registered iOS services without editing Android files."""
import argparse
import base64
import json
import plistlib
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SAMPLE_APP = 'ca-app-pub-3940256099942544~1458002511'


def configure(args):
    config = json.loads(Path(args.config).read_text()) if args.config else {}
    defines = {'IOS_LOCAL_ONLY': bool(args.local), 'IOS_APPLE_BILLING_ENABLED': False,
               'IOS_DISABLE_ADS': bool(args.local)}
    values = {
        'IOS_CONFIGURATION_KIND': 'local' if args.local else 'development',
        'IOS_ADMOB_APP_ID': SAMPLE_APP,
        'IOS_GOOGLE_CLIENT_ID': 'local-not-configured',
        'IOS_GOOGLE_REVERSED_CLIENT_ID': 'com.warrantycave.local',
    }
    if args.local:
        if args.release or args.firebase_plist or args.config:
            raise ValueError('--local cannot use production or Firebase configuration.')
        # Do not overwrite/remove a real Firebase registration when switching
        # the Dart app to local-only testing on the same Mac.
    else:
        if not args.firebase_plist:
            raise ValueError('Supply --firebase-plist for the registered iOS app, or --local for a simulator.')
        source = Path(args.firebase_plist).resolve()
        firebase = plistlib.loads(source.read_bytes())
        if (firebase.get('PROJECT_ID') != 'warrantycave' or
                firebase.get('BUNDLE_ID') != 'com.warrantycave.app' or
                ':ios:' not in firebase.get('GOOGLE_APP_ID', '')):
            raise ValueError('Use the WarrantyCave Firebase iOS registration for com.warrantycave.app.')
        for source_key, target_key in [('CLIENT_ID', 'IOS_GOOGLE_CLIENT_ID'),
                                       ('REVERSED_CLIENT_ID', 'IOS_GOOGLE_REVERSED_CLIENT_ID')]:
            value = firebase.get(source_key, '')
            if not re.fullmatch(r'[A-Za-z0-9._-]+', value):
                raise ValueError('The Firebase plist must include the enabled Google iOS client and URL scheme.')
            values[target_key] = value
        destination = ROOT / 'ios/Runner/GoogleService-Info.plist'
        if source != destination.resolve():
            shutil.copyfile(source, destination)
        defines['IOS_APPLE_BILLING_ENABLED'] = config.get('appleBillingEnabled') is True
        for field, native_key, dart_key, pattern in [
            ('admobAppId', 'IOS_ADMOB_APP_ID', None, r'ca-app-pub-\d{16}~\d{10}'),
            ('admobBannerId', None, 'IOS_ADMOB_BANNER_ID', r'ca-app-pub-\d{16}/\d{10}'),
            ('admobInlineBannerId', None, 'IOS_ADMOB_INLINE_BANNER_ID', r'ca-app-pub-\d{16}/\d{10}'),
            ('appStoreId', None, 'IOS_APP_STORE_ID', r'[1-9]\d{5,15}'),
            ('teamId', 'DEVELOPMENT_TEAM', None, r'[A-Z0-9]{10}'),
        ]:
            value = str(config.get(field, ''))
            if not value:
                if args.release:
                    raise ValueError(f'Release configuration requires {field}.')
                continue
            if not re.fullmatch(pattern, value):
                raise ValueError(f'Invalid {field}.')
            if args.release and (value.startswith('ca-app-pub-3940256099942544') or
                                value in {'ca-app-pub-1171723950608276/9463569777',
                                          'ca-app-pub-1171723950608276/9035972595'}):
                raise ValueError('Release requires the real iOS AdMob IDs.')
            if native_key:
                values[native_key] = value
            if dart_key:
                defines[dart_key] = value
        if args.release:
            if not defines['IOS_APPLE_BILLING_ENABLED']:
                raise ValueError('Configure and sandbox-test Apple billing before enabling a release.')
            values['IOS_CONFIGURATION_KIND'] = 'release'
    (ROOT / '.ios-dart-defines.json').write_text(json.dumps(defines, indent=2) + '\n')
    (ROOT / 'ios/Flutter/ServiceConfig.xcconfig').write_text(
        '// Generated by scripts/configure_ios.py; do not commit.\n' +
        ''.join(f'{key} = {value}\n' for key, value in values.items()))
    for name in ['DejaVuSans.ttf', 'DejaVuSans-Bold.ttf']:
        source = ROOT / 'assets/fonts' / (name + '.b64')
        (ROOT / 'assets/fonts' / name).write_bytes(base64.b64decode(source.read_bytes()))
    print(f"Prepared iOS {values['IOS_CONFIGURATION_KIND']} configuration.")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--local', action='store_true')
    parser.add_argument('--firebase-plist')
    parser.add_argument('--config', help='Private JSON with the real iOS service IDs.')
    parser.add_argument('--release', action='store_true')
    try:
        configure(parser.parse_args())
    except (ValueError, OSError, plistlib.InvalidFileException) as error:
        parser.exit(1, f'{error}\n')
