"""Generate the new typed Dart dictionaries; preserve placeholders exactly."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = (root / 'tool/new-locales.tsv').read_text().splitlines()
codes = rows[0].split('|')[1:]
maps = {code: {} for code in codes}
for row in rows[1:]:
    cells = row.split('|')
    assert len(cells) == 4, row
    key = cells[0]
    for code, value in zip(codes, cells[1:]):
        assert key not in maps[code], key
        maps[code][key] = value.replace('\\n', '\n')

