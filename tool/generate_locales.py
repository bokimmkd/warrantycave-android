for code, entries in maps.items():
    assert set(english) <= set(entries), (code, set(english) - set(entries))
    for key, value in english.items():
        assert sorted(re.findall(r'\{\w+\}', value)) == sorted(re.findall(r'\{\w+\}', entries[key])), (code, key)

def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
output = '// Generated by tool/generate_locales.py from reviewed locale text.\n'
output += 'const additionalTranslations = <String, Map<String, String>>{\n'
for code, entries in maps.items():
    output += f'  {dart(code)}: {{\n'
    output += ''.join(f'    {dart(key)}: {dart(value)},\n' for key, value in entries.items())
    output += '  },\n'
output += '};\n'
(root / 'lib/l10n/additional_translations.dart').write_text(output)
print('Generated:', {code: len(entries) for code, entries in maps.items()})
